// Exports the engine's JSON schemas and turns them into src/api/types.gen.ts.
import { execFileSync } from 'node:child_process'
import { copyFileSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const here = dirname(fileURLToPath(import.meta.url))
const clientDir = resolve(here, '..')
const pyDir = resolve(clientDir, '..', 'py')
const python = process.env.SCANSIM_PY ?? '/mnt/miniconda3/envs/ctm/bin/python'

// Pydantic titles every property ("Key", "Type", ...), which would become clashing
// top-level aliases. Keep titles only on the model definitions themselves.
function stripPropertyTitles(node, isModel = true) {
  if (Array.isArray(node)) return node.map((n) => stripPropertyTitles(n, false))
  if (node === null || typeof node !== 'object') return node
  const result = {}
  for (const [key, value] of Object.entries(node)) {
    if (key === 'title' && !isModel) continue
    if (key === '$defs') {
      result[key] = Object.fromEntries(
        Object.entries(value).map(([name, def]) => [name, stripPropertyTitles(def, true)]),
      )
    } else if (key === 'properties') {
      result[key] = Object.fromEntries(
        Object.entries(value).map(([name, prop]) => [name, stripPropertyTitles(prop, false)]),
      )
    } else {
      result[key] = stripPropertyTitles(value, false)
    }
  }
  return result
}

const readSchema = (dir, name) => stripPropertyTitles(JSON.parse(readFileSync(join(dir, name), 'utf8')))

const out = mkdtempSync(join(tmpdir(), 'scansim-schema-'))
try {
  execFileSync(python, ['-m', 'scansim.tools.export_schema', out], { cwd: pyDir, stdio: 'inherit' })
  const banner = '/* Generated by scripts/gen-types.mjs from the Python models. Do not edit. */\n'
  const opts = { bannerComment: '', additionalProperties: false, format: true }
  const snapshot = await compile(readSchema(out, 'snapshot.schema.json'), 'Snapshot', opts)
  const actions = await compile(readSchema(out, 'actions.schema.json'), 'Action', opts)
  writeFileSync(join(clientDir, 'src/api/types.gen.ts'), `${banner}\n${snapshot}\n${actions}`)
  copyFileSync(join(out, 'snapshot.sample.json'), join(clientDir, 'src/test/sampleSnapshot.json'))
} finally {
  rmSync(out, { recursive: true, force: true })
}
